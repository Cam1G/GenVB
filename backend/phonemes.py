def get_batches() -> Dict[int, List[Dict[str, Any]]]:
    """Group phoneme inventory items by their batch number (1..4)."""
    batches: Dict[int, List[Dict[str, Any]]] = {}
    for item in PHONEME_INVENTORY:
        b = item["batch"]
        batches.setdefault(b, []).append(item)
    return batches


def get_phoneme_by_alias(alias: str) -> Dict[str, Any]:
    """Find the phoneme item matching a given UTAU alias (with fallback to '01_aa')."""
    norm = alias.strip().lower()
    for item in PHONEME_INVENTORY:
        if item["id"] == norm or item["arpabet"] == norm or norm in [a.lower() for a in item["aliases"]]:
            return item
    for item in PHONEME_INVENTORY:
        for a in item["aliases"]:
            if norm in a.lower() or a.lower() in norm:
                return item
    return PHONEME_INVENTORY[0]
